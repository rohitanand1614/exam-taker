"""Download the web fonts and KaTeX that the app serves from its own `static/` folder (Batch 10b.2).

    python tools/fetch_assets.py            # (re)build static/fonts and static/katex
    python tools/fetch_assets.py --check    # only verify that every file is present (no network)

Why: the app must look right with no internet. Streamlit serves `static/` at `/app/static/...` when
`server.enableStaticServing = true` (see .streamlit/config.toml). Nothing here runs at app start-up.

What is fetched (all licences allow bundling; the licence files are saved next to the fonts):
  * Literata (variable, wght 400-600), Atkinson Hyperlegible 400/700, JetBrains Mono 400   - SIL Open Font License 1.1
  * KaTeX 0.16.11 (css, js, auto-render, woff2 fonts)                                      - MIT License
The font files are exactly the woff2 subsets Google Fonts serves for the same families, so the look is identical;
`static/fonts/fonts.css` carries their @font-face rules (with unicode-range).
"""
import argparse
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "static" / "fonts"
KATEX = ROOT / "static" / "katex"

URL_PREFIX = "/app/static"
KATEX_VERSION = "0.16.11"
KATEX_BASE = f"https://cdn.jsdelivr.net/npm/katex@{KATEX_VERSION}/dist"
KATEX_FONT_RE = re.compile(r"url\(fonts/(KaTeX_[A-Za-z0-9_-]+\.woff2)\)")

GOOGLE_CSS = ("https://fonts.googleapis.com/css2?family=Atkinson+Hyperlegible:wght@400;700"
              "&family=JetBrains+Mono:wght@400&family=Literata:opsz,wght@7..72,400;7..72,500;7..72,600"
              "&display=swap")
CHROME_UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36"

LICENCES = {                                    # file name -> source
    "OFL-Literata.txt": "https://raw.githubusercontent.com/googlefonts/literata/main/OFL.txt",
    "OFL-Atkinson-Hyperlegible.txt": "https://raw.githubusercontent.com/googlefonts/atkinson-hyperlegible/main/OFL.txt",
    "OFL-JetBrains-Mono.txt": "https://raw.githubusercontent.com/JetBrains/JetBrainsMono/master/OFL.txt",
}
KATEX_LICENCE = f"https://raw.githubusercontent.com/KaTeX/KaTeX/v{KATEX_VERSION}/LICENSE"

BLOCK_RE = re.compile(r"/\* ([\w-]+) \*/\s*@font-face \{(.*?)\}", re.S)


def get(url: str, ua: str = CHROME_UA) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": ua})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read()


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def fetch_fonts() -> list[str]:
    """Download every woff2 subset and write fonts.css. Returns the written file names."""
    FONTS.mkdir(parents=True, exist_ok=True)
    css = get(GOOGLE_CSS).decode("utf-8")
    written, by_url, rules = [], {}, []
    for subset, body in BLOCK_RE.findall(css):
        family = re.search(r"font-family: '([^']+)'", body).group(1)
        weight = re.search(r"font-weight: ([^;]+);", body).group(1).strip()
        style = re.search(r"font-style: ([^;]+);", body).group(1).strip()
        url = re.search(r"url\(([^)]+)\)", body).group(1)
        unicode_range = re.search(r"unicode-range: ([^;]+);", body).group(1).strip()
        if url not in by_url:                                    # Literata: one variable file serves 400/500/600
            name = f"{slug(family)}-{subset}-{len(by_url)}.woff2"
            (FONTS / name).write_bytes(get(url))
            by_url[url] = name
            written.append(name)
        rules.append(
            f"/* {family} {subset} */\n@font-face {{\n  font-family: '{family}';\n  font-style: {style};\n"
            f"  font-weight: {weight};\n  font-display: swap;\n  src: url({URL_PREFIX}/fonts/{by_url[url]}) format('woff2');\n"
            f"  unicode-range: {unicode_range};\n}}\n")
    (FONTS / "fonts.css").write_text(
        "/* generated by tools/fetch_assets.py - do not edit */\n" + "\n".join(rules), encoding="utf-8")
    for name, src in LICENCES.items():
        (FONTS / name).write_bytes(get(src))
        written.append(name)
    return written + ["fonts.css"]


def fetch_katex() -> list[str]:
    (KATEX / "fonts").mkdir(parents=True, exist_ok=True)
    css = get(f"{KATEX_BASE}/katex.min.css").decode("utf-8")
    fonts = sorted(set(KATEX_FONT_RE.findall(css)))
    for f in fonts:
        (KATEX / "fonts" / f).write_bytes(get(f"{KATEX_BASE}/fonts/{f}"))
    # keep only the woff2 source of every font (all current browsers); the woff/ttf fallbacks would 404
    css = re.sub(r",url\(fonts/[^)]+\.woff\) format\(\"woff\"\),url\(fonts/[^)]+\.ttf\) format\(\"truetype\"\)", "", css)
    css = css.replace("url(fonts/", f"url({URL_PREFIX}/katex/fonts/")
    (KATEX / "katex.min.css").write_text(css, encoding="utf-8")
    (KATEX / "katex.min.js").write_bytes(get(f"{KATEX_BASE}/katex.min.js"))
    (KATEX / "auto-render.min.js").write_bytes(get(f"{KATEX_BASE}/contrib/auto-render.min.js"))
    (KATEX / "LICENSE").write_bytes(get(KATEX_LICENCE))
    return ["katex.min.css", "katex.min.js", "auto-render.min.js", "LICENSE"] + [f"fonts/{f}" for f in fonts]


def expected_files() -> list[Path]:
    """Files the app needs (read from the generated css, so --check works offline)."""
    files = [FONTS / "fonts.css", KATEX / "katex.min.css", KATEX / "katex.min.js", KATEX / "auto-render.min.js"]
    files += [FONTS / n for n in LICENCES] + [KATEX / "LICENSE"]
    if (FONTS / "fonts.css").exists():
        files += [FONTS / n for n in re.findall(r"/fonts/([\w.-]+\.woff2)", (FONTS / "fonts.css").read_text("utf-8"))]
    if (KATEX / "katex.min.css").exists():
        files += [KATEX / "fonts" / n for n in re.findall(r"/katex/fonts/([\w.-]+\.woff2)",
                                                          (KATEX / "katex.min.css").read_text("utf-8"))]
    return files


def check() -> int:
    missing = [p for p in expected_files() if not p.exists() or p.stat().st_size == 0]
    for p in missing:
        print("missing:", p.relative_to(ROOT))
    print("ok" if not missing else f"{len(missing)} file(s) missing: run python tools/fetch_assets.py")
    return 1 if missing else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="only verify the files exist (no network)")
    args = ap.parse_args()
    if args.check:
        return check()
    fonts, katex = fetch_fonts(), fetch_katex()
    total = sum(p.stat().st_size for p in FONTS.rglob("*") if p.is_file()) + \
        sum(p.stat().st_size for p in KATEX.rglob("*") if p.is_file())
    print(f"fonts: {len(fonts)} files, katex: {len(katex)} files, {total / 1024:.0f} KiB in static/")
    return check()


if __name__ == "__main__":
    sys.exit(main())
